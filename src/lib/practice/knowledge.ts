export const ARTICLES: KnowledgeArticle[] = [...anatomy, ...emergency, ...reference];

export const findArticle = (id: string) => ARTICLES.find((a) => a.id === id);

/** Body systems link to the 3D atlas (public/anatomy). */
export const hasAtlas = (a: KnowledgeArticle) => a.kind === "anatomy";

/** One key fact a day for «Нүүр». */
export function factOfTheDay(date = new Date()): { fact: string; article: KnowledgeArticle } {
  const pairs = ARTICLES.flatMap((article) => article.keyFacts.map((fact) => ({ fact, article })));
  return pairs[Math.floor(date.getTime() / 86_400_000) % pairs.length];
}
